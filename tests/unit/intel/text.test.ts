import { describe, expect, it } from "vitest";
import { chunkFile } from "@/lib/intel/chunk";
import { extractCitations, linkCitations } from "@/lib/intel/citations";
import { looksGenerated, wantFile } from "@/lib/intel/files";
import { fuseRankings, queryTerms, searchDocument, splitIdentifiers, toTsQuery } from "@/lib/intel/text";

describe("search text", () => {
  it("splits identifiers into words", () => {
    expect(splitIdentifiers("getGitHubToken MAX_FILE_BYTES parseURLPath")).toEqual(
      expect.arrayContaining(["get", "git", "hub", "token", "parse", "url", "path"]),
    );
  });

  it("builds a safe OR tsquery and drops stop words", () => {
    expect(queryTerms("How does the rate limiter work?")).toEqual(["rate", "limiter"]);
    expect(toTsQuery("getSession'); DROP TABLE x;--")).toBe("getsession:* | drop:* | table:* | get:* | session:*");
    expect(toTsQuery("how is it?")).toBeNull();
  });

  it("adds path words and split identifiers to the search document", () => {
    const doc = searchDocument("src/lib/rate-limit.ts", ["rateLimit"], "export function rateLimit() {}");
    expect(doc).toContain("rate limit");
    expect(doc).toContain("src/lib/rate-limit.ts");
  });

  it("fuses rankings so items found by both retrievers win", () => {
    const scores = fuseRankings([
      ["a", "b", "c"],
      ["c", "d"],
    ]);
    const order = [...scores].sort((x, y) => y[1] - x[1]).map(([id]) => id);
    expect(order[0]).toBe("c");
  });
});

describe("chunkFile", () => {
  it("keeps whole definitions together and covers every line", () => {
    const lines = Array.from({ length: 300 }, (_, i) => `line ${i + 1}`);
    const symbols = [
      { name: "a", kind: "function", startLine: 1, endLine: 40, exported: true },
      { name: "b", kind: "function", startLine: 41, endLine: 140, exported: false },
      { name: "c", kind: "function", startLine: 141, endLine: 300, exported: false },
    ];
    const chunks = chunkFile(lines.join("\n"), symbols);
    expect(chunks[0]).toMatchObject({ startLine: 1, endLine: 40, symbols: ["a"] });
    expect(chunks[1]).toMatchObject({ startLine: 41, endLine: 140, symbols: ["b"] });
    expect(chunks.every((c) => c.endLine - c.startLine < 120)).toBe(true);
    const covered = chunks.reduce((n, c) => n + (c.endLine - c.startLine + 1), 0);
    expect(covered).toBe(300);
    expect(chunks.at(-1)!.endLine).toBe(300);
  });

  it("windows files without definitions, letting a short tail join the last window", () => {
    const chunks = chunkFile(Array.from({ length: 250 }, () => "x").join("\n"), []);
    expect(chunks.map((c) => [c.startLine, c.endLine])).toEqual([
      [1, 60],
      [61, 120],
      [121, 180],
      [181, 250],
    ]);
  });
});

describe("file filter", () => {
  it("keeps source and docs, skips vendored, lockfiles, binaries and huge files", () => {
    expect(wantFile("src/index.ts", 100)).toBe(true);
    expect(wantFile("docs/guide.md", 100)).toBe(true);
    expect(wantFile("node_modules/x/index.js", 100)).toBe(false);
    expect(wantFile("package-lock.json", 100)).toBe(false);
    expect(wantFile("public/logo.png", 100)).toBe(false);
    expect(wantFile("dist/app.min.js", 100)).toBe(false);
    expect(wantFile("src/index.ts", 10_000_000)).toBe(false);
  });

  it("detects minified and generated files", () => {
    expect(looksGenerated("a".repeat(5000))).toBe(true);
    expect(looksGenerated("// Code generated by protoc. DO NOT EDIT.\n" + "x\n".repeat(3000))).toBe(true);
    expect(looksGenerated("const a = 1;\n".repeat(400))).toBe(false);
  });
});

describe("citations", () => {
  const text = "See [src/a.ts:L3-L9] and [src/b.ts:L4], the [README.md] and [src/made-up.ts:L1]. Not [a link](x) or [note].";

  it("extracts citation markers", () => {
    expect(extractCitations(text).map((c) => `${c.path}:${c.startLine}-${c.endLine}`)).toEqual([
      "src/a.ts:3-9",
      "src/b.ts:4-4",
      "README.md:1-1",
      "src/made-up.ts:1-1",
    ]);
  });

  it("links only files that exist", () => {
    const known = new Set(["src/a.ts", "src/b.ts", "README.md"]);
    const out = linkCitations(text, (p) => known.has(p), (c) => `/x?p=${c.path}#L${c.startLine}`);
    expect(out).toContain("[src/a.ts:L3-L9](/x?p=src/a.ts#L3)");
    expect(out).toContain("[src/b.ts:L4](/x?p=src/b.ts#L4)");
    expect(out).toContain("[README.md](/x?p=README.md#L1)");
    expect(out).toContain("[src/made-up.ts:L1].");
    expect(out).toContain("[a link](x)");
  });

  it("reads Next.js [param] and (group) folders in paths", () => {
    const found = extractCitations("See [src/app/a/[slug]/page.tsx:L3-L9] and [src/app/(marketing)/pr/page.tsx].");
    expect(found.map((c) => `${c.path}:${c.startLine}-${c.endLine}`)).toEqual(["src/app/a/[slug]/page.tsx:3-9", "src/app/(marketing)/pr/page.tsx:1-1"]);
  });

  it("can label links with a short name", () => {
    const out = linkCitations("[src/a.ts:L3-L9]", () => true, () => "#x", (p) => p.split("/").pop()!);
    expect(out).toBe("[a.ts:L3-L9](#x)");
  });
});
